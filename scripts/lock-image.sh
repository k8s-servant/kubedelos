#!/usr/bin/env bash
# Regenerate the container image's hashed lock files: requirements/image.txt (the runtime dependencies in
# pyproject.toml) and requirements/build.txt (the build backend, from requirements/build.in). The Dockerfile installs
# them with --require-hashes, so two builds of one commit install the same files and a changed hash fails the build.
# One lock serves amd64 and arm64: it is resolved for the image's Python on musl Linux and lists the hashes of every
# file each pinned release publishes. Needs uv. Run it after changing a dependency; tests/test_packaging.py fails when
# the lock no longer satisfies pyproject.toml.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# The image's Python (the Dockerfile's base) and platform.
TARGET=(--python-version 3.14 --python-platform x86_64-unknown-linux-musl)

lock() { # output, inputs...
  local out="$1"
  shift
  uv pip compile "$@" "${TARGET[@]}" --generate-hashes --no-header --quiet --output-file "$out.tmp"
  {
    echo "# Generated by scripts/lock-image.sh from $*; do not edit."
    cat "$out.tmp"
  } >"$out"
  rm -f "$out.tmp"
}

lock requirements/image.txt pyproject.toml
lock requirements/build.txt requirements/build.in
